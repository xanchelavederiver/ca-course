"""Gauss (Lagrange) reduction of a two-dimensional lattice, exactly in integers.

The algorithm of Hoffstein--Pipher--Silverman, 2nd ed., Section 7.13.1:

    loop
        if |v2| < |v1|: swap v1, v2
        m = round(<v1, v2> / |v1|^2)
        if m = 0: return v1, v2
        v2 = v2 - m v1

On return |v1| <= |v2| and |<v1, v2>| <= |v1|^2 / 2, so v1 is a shortest nonzero vector
of the lattice and v2 a shortest vector independent of v1: the answer is exact, which is
why the spec asks for Gauss (and not LLL) in dimension 2.

Only integer arithmetic is used (squared norms, nearest-integer division). The vectors may
live in Z^m for any m. Collinear input (a rank-1 "lattice") is accepted: then the loop is
Euclid's algorithm in disguise, v2 becomes 0 and the answer is the single generator.
"""

from __future__ import annotations

from lattice import as_basis, dot, round_div


def gauss_reduce(basis, trace: bool = True) -> tuple[list[list[int]], dict]:
    """Gauss-reduce two integer vectors. Returns (basis, extra); the basis has 2 vectors,
    or 1 (0) if the input vectors are collinear (both zero)."""
    b = as_basis(basis)
    if len(b) != 2:
        raise ValueError(f"Gauss reduction needs exactly 2 vectors, got {len(b)}")
    v1, v2 = b
    steps = []                     # (v1, v2) after every iteration of the loop
    swaps = iterations = 0
    while True:
        n1, n2 = dot(v1, v1), dot(v2, v2)
        if n2 < n1:
            v1, v2, n1, n2 = v2, v1, n2, n1
            swaps += 1
        if n1 == 0:                # v1 = 0: the lattice is generated by v2 alone
            red = [v2] if n2 else []
            break
        m = round_div(dot(v1, v2), n1)
        if m == 0:
            red = [v1, v2]
            break
        v2 = [y - m * x for x, y in zip(v1, v2)]
        iterations += 1
        if trace:
            steps.append({"m": m, "v1": list(v1), "v2": list(v2)})
    extra = {"iterations": iterations, "swaps": swaps, "rank": len(red),
             "norms2": [dot(v, v) for v in red]}
    if trace:
        extra["trace"] = steps
    return red, extra
