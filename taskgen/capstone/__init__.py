"""Capstone (мини-курсовая) pipeline: test vectors, benchmarks, requirements, checker.

Instructor-only (students get just the spec PDF). Layout::

    materials/capstone/capstone.yaml          shared defaults (slack, timeout) + the list
    materials/capstone/NN-slug/
        spec.tex                              ca-capstone spec, \\input{requirements}
        requirements.tex                      generated by `report` (\\Req... macros)
        reference/                            reference implementation (CLI, see below)
        vectors/<size>.jsonl, manifest.json   generated by `vectors` (seeded)
        bench/config.yaml                     generator, command, size classes, requirements
        bench/results.json, results.md, plot.{png,pdf}   generated by `report`
    taskgen/capstone/gens/<name>.py           per-capstone instance generator + verifier

**Vector file** (JSON lines): ``{"id", "size", "tags", "input", "expected"}``.

**Solver contract** (reference implementations and, through an adapter, student
submissions): a long-running process reads JSON lines ``{"id": ..., "input": {...}}``
on stdin and answers each with one JSON line ``{"id": ..., "output": {...}}``
(optionally ``"extra": {...}`` — intermediate data, e.g. the CRT system — or
``"error": "..."``) on stdout, flushing after every line. Timing is the wall time
between writing a request and reading its answer.

**Generator module** (``gens/<name>.py``)::

    VERSION = 1                                   # bump when output changes for a seed
    def generate(params: dict, rng: random.Random) -> dict   # {"input", "expected", "tags"}
    def verify(vector: dict, output: dict) -> str | None     # None = correct, else why not

``generate`` may use Sage (import it inside the function) but must draw randomness only
from ``rng``. ``verify`` must accept every correct answer (not only ``expected``) and,
for capstones whose image has no Sage (``capstone-c``), use the standard library only.

Entry point: ``python -m taskgen.capstone`` (see ``__main__``); it must not import Sage
or ``taskgen.core`` at module level, since it also runs in the ``capstone-c`` image.
"""
