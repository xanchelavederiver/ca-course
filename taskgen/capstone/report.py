"""Benchmark report: ``bench/results.json``, ``bench/results.md``, ``bench/plot.{png,pdf}``
and the spec's ``requirements.tex``.

Requirement macros (``requirements:`` in ``bench/config.yaml``)::

    ReqBits:    {value: 100}                    # a literal (number or text)
    ReqSeconds: {size: p100, stat: max}         # slack * stat of the class's wall times
                 # stat: max | median | mean | p90       (default max); with the suffix
                 #       _op (max_op, median_op, ...): per operation, i.e. wall / input.repeat
                 # unit: s | ms | us                     (default s)
                 # round: nice (1-2-5 series, up) | ceil | none   (default nice)
                 # slack: false                          (report the measured value itself)
                 # min: 1                                (floor, in `unit`)

``\\ReqSlack`` (the slack factor) is always defined. Numbers use a decimal comma.
"""

from __future__ import annotations

import json
import math
import statistics
from pathlib import Path

from taskgen.capstone.config import Capstone

UNITS = {"s": 1.0, "ms": 1e-3, "us": 1e-6}
STATUSES = ("ok", "wrong", "error", "timeout", "crash")


def nice_up(x: float) -> float:
    """Smallest 1/2/5 x 10^k that is >= x."""
    if x <= 0:
        return 0.0
    e = math.floor(math.log10(x))
    for m in (1, 2, 5, 10):
        v = m * 10.0 ** e
        if v >= x * (1 - 1e-12):
            return float(f"{v:.12g}")
    return 10.0 ** (e + 1)


def fmt_num(x: float | int | str) -> str:
    if isinstance(x, str):
        return x
    if float(x).is_integer():
        return str(int(x))
    return f"{x:.3g}".replace(".", "{,}")


def _stat(xs: list[float], stat: str) -> float:
    if not xs:
        return float("nan")
    if stat == "max":
        return max(xs)
    if stat == "median":
        return statistics.median(xs)
    if stat == "mean":
        return statistics.fmean(xs)
    if stat == "p90":
        s = sorted(xs)
        return s[min(len(s) - 1, math.ceil(0.9 * len(s)) - 1)]
    raise ValueError(f"unknown stat {stat!r}")


def summarize(cap: Capstone, raw: dict) -> dict[str, dict]:
    out = {}
    for name in raw["sizes"]:
        rs = [r for r in raw["records"] if r["size"] == name]
        good = [r for r in rs if r["status"] == "ok" and r["wall_s"] is not None]
        walls = [r["wall_s"] for r in good]
        ops = [r["wall_s"] / max(1, r.get("repeat") or 1) for r in good]
        size = cap.size(name)
        s = {"x": size.x, "n": len(rs), **{k: sum(r["status"] == k for r in rs) for k in STATUSES},
             "median_s": _stat(walls, "median") if walls else None,
             "mean_s": _stat(walls, "mean") if walls else None,
             "p90_s": _stat(walls, "p90") if walls else None,
             "max_s": max(walls) if walls else None,
             "max_rss_kb": max((r["rss_kb"] or 0 for r in rs), default=None) or None,
             "timeout_s": cap.timeout_for(size)}
        if any((r.get("repeat") or 1) > 1 for r in good):
            s.update({f"{k}_op_s": _stat(ops, k) for k in ("median", "mean", "p90", "max")})
        s["limit_s"] = cap.slack * s["max_s"] if s["max_s"] is not None else None
        out[name] = s
    return out


def requirements(cap: Capstone, summary: dict[str, dict]) -> tuple[dict[str, str], list[str]]:
    macros = {"ReqSlack": fmt_num(cap.slack)}
    warnings = []
    for name, spec in cap.requirements.items():
        if "value" in spec:
            macros[name] = fmt_num(spec["value"])
            continue
        s = summary.get(spec["size"])
        if s is None:
            warnings.append(f"{name}: size class {spec['size']!r} was not benchmarked")
            continue
        if s["n"] != s["ok"]:
            warnings.append(f"{name}: the reference failed {s['n'] - s['ok']} of {s['n']} "
                            f"vectors of {spec['size']}")
        stat = spec.get("stat", "max")
        val = s.get(f"{stat}_s")
        if val is None and stat.endswith("_op"):
            val = s.get(f"{stat[:-3]}_s")      # no repeats: per-op time = wall time
        if val is None:
            warnings.append(f"{name}: no successful runs in {spec['size']}")
            continue
        val /= UNITS[spec.get("unit", "s")]
        if spec.get("slack", True):
            val *= cap.slack
        val = max(val, float(spec.get("min", 0)))
        rnd = spec.get("round", "nice")
        val = nice_up(val) if rnd == "nice" else math.ceil(val) if rnd == "ceil" else val
        macros[name] = fmt_num(val)
    return macros, warnings


def requirements_tex(cap: Capstone, macros: dict[str, str]) -> str:
    lines = [f"% Generated by `make bench CAPSTONE={cap.slug}` (taskgen.capstone report) from",
             "% bench/results.json: reference time x slack on the reference machine.",
             "% Do not edit: change bench/config.yaml and re-run the benchmark."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    return "\n".join(lines) + "\n"


def markdown(cap: Capstone, summary: dict[str, dict], machine: dict, macros: dict[str, str]) -> str:
    def f(x, d=3):
        return "—" if x is None else f"{x:.{d}g}"

    rows = ["| size | x | ok/n | timeout | median, s | p90, s | max, s | limit (×{0:g}), s | peak RSS, MB |"
            .format(cap.slack), "|---|---|---|---|---|---|---|---|---|"]
    for name, s in summary.items():
        rows.append(f"| {name} | {fmt_x(s['x'])} | {s['ok']}/{s['n']} | {s['timeout']} | {f(s['median_s'])} "
                    f"| {f(s['p90_s'])} | {f(s['max_s'])} | {f(s['limit_s'])} | "
                    f"{'—' if not s['max_rss_kb'] else round(s['max_rss_kb'] / 1024)} |")
    m = ", ".join(f"{k}: {v}" for k, v in machine.items())
    req = "\n".join(f"- `\\{k}` = {v}" for k, v in macros.items())
    return (f"# {cap.title} — benchmark of the reference\n\n"
            f"Generated by `make bench CAPSTONE={cap.slug}`; do not edit.\n\n"
            f"Command: `{cap.command}`\n\nMachine: {m}\n\n" + "\n".join(rows)
            + f"\n\nDerived requirements (`requirements.tex`):\n\n{req}\n\n![time vs size](plot.png)\n")


def fmt_x(x) -> str:
    return "—" if x is None else (str(int(x)) if float(x).is_integer() else str(x))


def plot(cap: Capstone, summary: dict[str, dict], out_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    pts = [(s["x"], s) for s in summary.values() if s["x"] is not None and s["max_s"] is not None]
    if not pts:
        return []
    # With `repeat` the wall time per request is ~constant: plot the per-operation time.
    per_op = all("median_op_s" in s for _, s in pts)
    k = "_op_s" if per_op else "_s"
    xs = [x for x, _ in pts]
    fig, ax = plt.subplots(figsize=(6.4, 4.0))
    ax.plot(xs, [s["median" + k] for _, s in pts], "o-", color="#1f5fa8", label="медиана")
    ax.plot(xs, [s["max" + k] for _, s in pts], "s--", color="#c0392b", label="максимум")
    ax.plot(xs, [cap.slack * s["max" + k] for _, s in pts], ":", color="#555555",
            label=f"максимум × {fmt_num(cap.slack).replace('{,}', ',')}")
    ax.set_yscale("log")
    ax.set_xlabel(cap.x_label)
    ax.set_ylabel("время одной операции, с" if per_op else "время, с")
    ax.set_title(cap.title)
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()
    fig.tight_layout()
    paths = [out_dir / "plot.png", out_dir / "plot.pdf"]
    fig.savefig(paths[0], dpi=120, metadata={"Software": None})
    fig.savefig(paths[1], metadata={"CreationDate": None, "Creator": None, "Producer": None})
    plt.close(fig)
    return paths


def report(cap: Capstone, raw_path: Path, log=print) -> list[str]:
    """Write results.json/md, plot and requirements.tex; returns warnings."""
    raw = json.loads(raw_path.read_text(encoding="utf-8"))
    summary = summarize(cap, raw)
    macros, warnings = requirements(cap, summary)
    bd = cap.bench_dir
    results = {"capstone": cap.slug, "command": raw["command"], "slack": cap.slack,
               "started": raw["started"], "duration_s": raw["duration_s"],
               "machine": raw["machine"], "summary": summary, "requirements": macros,
               "warnings": warnings,
               "records": [{k: r.get(k) for k in ("id", "size", "tags", "status", "wall_s", "repeat", "rss_kb",
                                                 "message")}
                           for r in raw["records"]]}
    (bd / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=1) + "\n",
                                     encoding="utf-8")
    (bd / "results.md").write_text(markdown(cap, summary, raw["machine"], macros), encoding="utf-8")
    (cap.dir / "requirements.tex").write_text(requirements_tex(cap, macros), encoding="utf-8")
    for p in plot(cap, summary, bd):
        log(f"wrote {p.name}")
    log(f"wrote bench/results.json, bench/results.md, requirements.tex ({cap.slug})")
    for w in warnings:
        log(f"WARNING: {w}")
    return warnings
