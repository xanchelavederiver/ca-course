"""Course map (``course.yaml``): lectures, seminars, topics and exam questions.

The map is the single source of truth for the course materials (Plan 3)::

    semesters:
      - n: 1
        exam_questions: 22               # size of the semester's exam question list
        lectures:
          - n: 2
            slug: big-integer-arithmetic
            title: Арифметика больших чисел
            topics: [arithmetic.multiplication]
            exam_questions: [sem1:1, sem1:5]
            legacy_deck: "tmp/лекции/Lecture 2. ....pptx"
        seminars:
          - n: 1
            slug: karatsuba-toom-cook
            title: Умножение больших чисел
            lectures: [2]
            # sheet: sheets/sem1/seminar-01-karatsuba-toom-cook.yaml   (default)

This module loads and checks the map (``check``), creates missing material
directories from the templates (``scaffold``), renders taskgen worked examples
for lecture notes (``examples``), lists the documents to build (``documents``)
and writes the per-semester book of lecture notes (``book_tex``).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

REPO_ROOT = Path(__file__).resolve().parents[2]
COURSE_FILE = REPO_ROOT / "course.yaml"
MATERIALS = "materials"
SLUG = r"^[a-z0-9][a-z0-9-]*$"
QUESTION = re.compile(r"^sem(\d+):(\d+)$")
TEMPLATE_DIR = "00-template"


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Lecture(_Model):
    n: int = Field(ge=1)
    slug: str = Field(pattern=SLUG)
    title: str
    topics: list[str] = []
    exam_questions: list[str] = []
    legacy_deck: str | None = None
    draft: bool = False

    def dir(self, sem: int) -> str:
        return f"{MATERIALS}/sem{sem}/lectures/{self.n:02d}-{self.slug}"


class Seminar(_Model):
    n: int = Field(ge=1)
    slug: str = Field(pattern=SLUG)
    title: str
    lectures: list[int] = []
    sheet: str | None = None
    draft: bool = False

    def dir(self, sem: int) -> str:
        return f"{MATERIALS}/sem{sem}/seminars/{self.n:02d}-{self.slug}"

    def sheet_path(self, sem: int) -> str:
        return self.sheet or f"sheets/sem{sem}/seminar-{self.n:02d}-{self.slug}.yaml"


class Semester(_Model):
    n: int = Field(ge=1)
    title: str
    exam: str = ""
    exam_questions: int = 0
    lectures: list[Lecture] = []
    seminars: list[Seminar] = []

    @model_validator(mode="after")
    def _unique(self) -> "Semester":
        for kind, items in (("lecture", self.lectures), ("seminar", self.seminars)):
            for attr in ("n", "slug"):
                vals = [getattr(x, attr) for x in items]
                dup = sorted({str(v) for v in vals if vals.count(v) > 1})
                if dup:
                    raise ValueError(f"semester {self.n}: duplicate {kind} {attr}: {', '.join(dup)}")
        return self

    def lecture(self, n: int) -> Lecture | None:
        return next((lec for lec in self.lectures if lec.n == n), None)


class Course(_Model):
    semesters: list[Semester]

    def semester(self, n: int) -> Semester:
        for s in self.semesters:
            if s.n == n:
                return s
        raise KeyError(f"no semester {n} in course.yaml")


def load_course(path: str | Path = COURSE_FILE) -> Course:
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    return Course.model_validate(data)


# --- worked examples -----------------------------------------------------------------
#
# A lecture directory may hold ``examples.yaml``::
#
#     - name: xgcd                     # -> examples/xgcd.tex, \input{examples/xgcd}
#       task: number_theory.xgcd[@preset]
#       seed: 3
#       title: Расширенный алгоритм Евклида   # optional, the example's heading
#
# ``taskgen course examples`` renders every entry (generation validates the
# instance) into a committed LaTeX fragment; ``check`` reports stale fragments.

EXAMPLES_FILE = "examples.yaml"


class Example(_Model):
    name: str = Field(pattern=r"^[a-z0-9][a-z0-9_-]*$")
    task: str
    seed: int
    title: str | None = None


def load_examples(lecture_dir: Path) -> list[Example]:
    f = lecture_dir / EXAMPLES_FILE
    if not f.exists():
        return []
    return [Example.model_validate(e) for e in (yaml.safe_load(f.read_text(encoding="utf-8")) or [])]


def render_example(ex: Example) -> str:
    from taskgen.core import registry
    from taskgen.core.rng import make_rng

    inst = registry.get_task(ex.task).generate(make_rng(ex.seed), seed=ex.seed)
    title = f"[{ex.title}]" if ex.title else ""
    return (f"% Generated by `taskgen course examples` from {inst.ref} (seed {ex.seed}).\n"
            f"% Do not edit: change examples.yaml and regenerate.\n"
            f"\\begin{{example}}{title}\\label{{ex:{ex.name}}}\n"
            f"{inst.statement.strip()}\n\n"
            f"\\par\\noindent\\textit{{Решение.}} {inst.solution.strip()}\n"
            f"\\end{{example}}\n")


def example_path(lecture_dir: Path, ex: Example) -> Path:
    return lecture_dir / "examples" / f"{ex.name}.tex"


def examples(course: Course, repo: Path = REPO_ROOT, write: bool = True,
             sem: int | None = None, only: str | None = None) -> list[tuple[str, str]]:
    """Render all worked examples; returns ``(path, status)`` with status
    ``ok`` / ``written`` / ``stale`` (stale only when ``write`` is false) / ``error: ...``.
    ``only``: restrict to lecture directories containing this substring."""
    out = []
    for s in course.semesters:
        if sem is not None and s.n != sem:
            continue
        for lec in s.lectures:
            if only and only not in lec.dir(s.n):
                continue
            d = repo / lec.dir(s.n)
            try:
                exs = load_examples(d)
            except Exception as e:
                out.append((f"{lec.dir(s.n)}/{EXAMPLES_FILE}", f"error: {e}"))
                continue
            for ex in exs:
                p = example_path(d, ex)
                rel = str(p.relative_to(repo))
                try:
                    text = render_example(ex)
                except Exception as e:
                    out.append((rel, f"error: {type(e).__name__}: {e}"))
                    continue
                if p.exists() and p.read_text(encoding="utf-8") == text:
                    out.append((rel, "ok"))
                elif write:
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_text(text, encoding="utf-8")
                    out.append((rel, "written"))
                else:
                    out.append((rel, "stale"))
    return out


# --- checks ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Problem:
    level: Literal["error", "warning"]
    where: str
    message: str

    def __str__(self) -> str:
        return f"{self.level.upper():<7} {self.where}: {self.message}"


def _questions(course: Course) -> dict[str, list[str]]:
    """question id -> lectures covering it"""
    cov: dict[str, list[str]] = {}
    for s in course.semesters:
        for k in range(1, s.exam_questions + 1):
            cov[f"sem{s.n}:{k}"] = []
        for lec in s.lectures:
            for q in lec.exam_questions:
                cov.setdefault(q, []).append(f"sem{s.n}/{lec.n:02d}")
    return cov


def check(course: Course, repo: Path = REPO_ROOT, examples_stale: bool = True) -> list[Problem]:
    """Consistency of the course map with the taxonomy, the tasks and the files.

    Missing files are errors for regular entries and warnings for ``draft``
    ones. ``examples_stale`` regenerates worked examples in memory (needs Sage).
    """
    from taskgen.core import registry
    from taskgen.core.sheet import ClassroomSheet, load_sheet
    from taskgen.core.taxonomy import check_topic, taxonomy

    probs: list[Problem] = []

    def add(level: str, where: str, msg: str) -> None:
        probs.append(Problem(level, where, msg))  # type: ignore[arg-type]

    tax = taxonomy()
    covered_topics: set[str] = set()
    known_dirs: set[str] = set()

    for s in course.semesters:
        labels: dict[str, str] = {}  # label -> lecture dir (unique within the semester book)
        for lec in s.lectures:
            where = lec.dir(s.n)
            known_dirs.add(where)
            miss = "warning" if lec.draft else "error"
            d = repo / where
            for t in lec.topics:
                bad = check_topic(t)
                if bad:
                    add("error", where, f"topic {t!r} not in taxonomy")
                    continue
                covered_topics.add(t)
                if not registry.tasks_matching([t]):
                    add("warning", where, f"topic {t!r} has no tasks")
            for q in lec.exam_questions:
                m = QUESTION.match(q)
                if not m:
                    add("error", where, f"bad exam question id {q!r} (expected sem<N>:<k>)")
                    continue
                try:
                    qs = course.semester(int(m.group(1)))
                except KeyError:
                    add("error", where, f"exam question {q!r}: no such semester")
                    continue
                if not 1 <= int(m.group(2)) <= qs.exam_questions:
                    add("error", where, f"exam question {q!r} out of range 1..{qs.exam_questions}")
            if not d.is_dir():
                add(miss, where, "directory missing (taskgen course scaffold)")
                continue
            for f in ("notes.tex", "notes-body.tex", "slides.tex"):
                if not (d / f).exists():
                    add(miss, where, f"{f} missing")
            try:
                exs = load_examples(d)
            except Exception as e:
                add("error", f"{where}/{EXAMPLES_FILE}", str(e))
                exs = []
            body = (d / "notes-body.tex").read_text(encoding="utf-8") if (d / "notes-body.tex").exists() else ""
            for ex in exs:
                if f"examples/{ex.name}" not in body and f"\\taskexample{{{ex.name}}}" not in body:
                    add("warning", f"{where}/{EXAMPLES_FILE}", f"example {ex.name!r} is not \\input in notes-body.tex")
            for ex in exs:
                lab = f"ex:{ex.name}"
                if lab in labels:
                    add("error", f"{where}/{EXAMPLES_FILE}", f"example name {ex.name!r} also used in {labels[lab]}")
                labels[lab] = where
            for lab in re.findall(r"\\label\{([^}]*)\}", re.sub(r"(?<!\\)%.*", "", body)):
                if lab in labels:
                    add("error", f"{where}/notes-body.tex", f"label {lab!r} also used in {labels[lab]}")
                labels[lab] = where
            if body and not re.search(r"\\begin\{lecture\}\{" + str(lec.n) + r"\}", body):
                add("error", f"{where}/notes-body.tex", f"expected \\begin{{lecture}}{{{lec.n}}}{{...}}")

        lecture_numbers = {lec.n for lec in s.lectures}
        for sem in s.seminars:
            where = sem.dir(s.n)
            known_dirs.add(where)
            miss = "warning" if sem.draft else "error"
            for ln in sem.lectures:
                if ln not in lecture_numbers:
                    add("error", where, f"unknown lecture {ln}")
            if not (repo / where / "handout.tex").exists():
                add(miss, where, "handout.tex missing")
            sp = repo / sem.sheet_path(s.n)
            if not sp.exists():
                add(miss, where, f"sheet {sem.sheet_path(s.n)} missing")
            else:
                try:
                    spec, _ = load_sheet(sp)
                    if not isinstance(spec, ClassroomSheet):
                        add("error", sem.sheet_path(s.n), "seminar sheet must be kind: classroom")
                except Exception as e:
                    add("error", sem.sheet_path(s.n), f"invalid sheet: {e}")

        # material directories that the map does not know (renamed / removed entries)
        for kind in ("lectures", "seminars"):
            base = repo / MATERIALS / f"sem{s.n}" / kind
            if base.is_dir():
                for d in sorted(base.iterdir()):
                    rel = f"{MATERIALS}/sem{s.n}/{kind}/{d.name}"
                    if d.is_dir() and d.name != TEMPLATE_DIR and rel not in known_dirs:
                        add("warning", rel, "directory not in course.yaml")

    for q, lecs in _questions(course).items():
        if not lecs:
            add("error", "course.yaml", f"exam question {q} is not covered by any lecture")

    # leaf topics with tasks that no lecture covers, and topics without tasks
    for t in tax:
        leaf = not any(o.startswith(t + ".") for o in tax)
        if not leaf:
            continue
        has_tasks = bool(registry.tasks_matching([t]))
        lectured = any(t == c or t.startswith(c + ".") for c in covered_topics)
        if not has_tasks:
            add("warning", "taxonomy", f"topic {t!r} has no tasks")
        if not lectured:
            add("warning", "taxonomy", f"topic {t!r} is not covered by any lecture")

    if examples_stale:
        for path, status in examples(course, repo, write=False):
            if status == "stale":
                add("error", path, "worked example is stale (taskgen course examples)")
            elif status.startswith("error"):
                add("error", path, status)
    return probs


# --- scaffold ------------------------------------------------------------------------------

def _subst(text: str, pattern: str, repl: str) -> str:
    new, n = re.subn(pattern, lambda _m: repl, text, count=1)
    return new if n else text


def scaffold(course: Course, repo: Path = REPO_ROOT, sem: int | None = None) -> list[str]:
    """Create missing lecture/seminar directories (and seminar sheets) from the templates."""
    created: list[str] = []
    for s in course.semesters:
        if sem is not None and s.n != sem:
            continue
        lec_tpl = repo / MATERIALS / "sem1" / "lectures" / TEMPLATE_DIR
        sem_tpl = repo / MATERIALS / "sem1" / "seminars" / TEMPLATE_DIR
        for lec in s.lectures:
            d = repo / lec.dir(s.n)
            if d.exists():
                continue
            d.mkdir(parents=True)
            for name in ("notes.tex", "notes-body.tex", "slides.tex"):
                text = (lec_tpl / name).read_text(encoding="utf-8")
                text = _subst(text, r"\\begin\{lecture\}\{\d+\}\{[^}\n]*\}",
                              f"\\begin{{lecture}}{{{lec.n}}}{{{lec.title}}}")
                text = _subst(text, r"\\lecture\{\d+\}\{[^}\n]*\}", f"\\lecture{{{lec.n}}}{{{lec.title}}}")
                text = re.sub(r"^% .*template.*\n", "", text, count=1, flags=re.M)
                text = text.replace("{l0:", f"{{l{lec.n}:")  # labels are prefixed by the lecture
                (d / name).write_text(text, encoding="utf-8")
            created.append(lec.dir(s.n))
        for sm in s.seminars:
            d = repo / sm.dir(s.n)
            if not d.exists():
                d.mkdir(parents=True)
                text = (sem_tpl / "handout.tex").read_text(encoding="utf-8")
                text = _subst(text, r"\\seminar\{\d+\}\{[^}\n]*\}", f"\\seminar{{{sm.n}}}{{{sm.title}}}")
                text = re.sub(r"^% .*template.*\n", "", text, count=1, flags=re.M)
                (d / "handout.tex").write_text(text, encoding="utf-8")
                created.append(sm.dir(s.n))
            sp = repo / sm.sheet_path(s.n)
            if not sp.exists():
                sp.parent.mkdir(parents=True, exist_ok=True)
                sp.write_text(_sheet_skeleton(course, s, sm), encoding="utf-8")
                created.append(sm.sheet_path(s.n))
    return created


def _sheet_skeleton(course: Course, s: Semester, sm: Seminar) -> str:
    from taskgen.core import registry

    refs: list[str] = []
    for ln in sm.lectures:
        lec = s.lecture(ln)
        for t in (lec.topics if lec else []):
            refs += [c.id for c in registry.tasks_matching([t]) if c.id not in refs]
    data: dict[str, Any] = {
        "id": f"sem{s.n}-seminar-{sm.n:02d}-{sm.slug}",
        "kind": "classroom",
        "title": f"Семинар {sm.n}. {sm.title}",
        "semester": s.n,
        "document": {"toc": False},
        "sections": [{"title": "Задачи", "tasks": refs or ["TODO"]}],
    }
    if s.n == 2:
        data["preset"] = "sem2"
    return ("# Classroom sheet (skeleton from `taskgen course scaffold`): order the tasks\n"
            "# warm-up -> core -> corner cases.\n"
            + yaml.safe_dump(data, allow_unicode=True, sort_keys=False))


# --- documents & the semester book ---------------------------------------------------------

def documents(course: Course, sem: int | None = None) -> list[str]:
    """LaTeX documents of the course map (notes, slides, handouts), in map order."""
    out = []
    for s in course.semesters:
        if sem is not None and s.n != sem:
            continue
        for lec in s.lectures:
            out += [f"{lec.dir(s.n)}/notes.tex", f"{lec.dir(s.n)}/slides.tex"]
        out += [f"{sm.dir(s.n)}/handout.tex" for sm in s.seminars]
    return out


def sheets(course: Course, sem: int | None = None) -> list[str]:
    return [sm.sheet_path(s.n) for s in course.semesters if sem is None or s.n == sem
            for sm in s.seminars]


BOOK_DIR = "build/materials"


def book_path(sem: int) -> str:
    return f"{BOOK_DIR}/sem{sem}/notes-book.tex"


def book_tex(course: Course, sem: int, repo: Path = REPO_ROOT) -> str:
    """The semester book: every lecture's ``notes-body.tex`` as a chapter."""
    s = course.semester(sem)
    up = Path(*[".."] * (len(Path(book_path(sem)).parent.parts)))
    lines = [
        "% Generated by `taskgen course book` from course.yaml. Do not edit.",
        "\\documentclass[book]{ca-notes}",
        f"\\coursebook{{{sem}}}{{{s.title}}}",
        "\\begin{document}",
        "\\makebooktitle",
    ]
    for lec in s.lectures:
        if (repo / lec.dir(s.n) / "notes-body.tex").exists():
            lines.append(f"\\subimport{{{(up / lec.dir(s.n)).as_posix()}/}}{{notes-body}}")
    lines += ["\\printcoursebibliography", "\\end{document}", ""]
    return "\n".join(lines)


def write_book(course: Course, sem: int, repo: Path = REPO_ROOT) -> Path:
    p = repo / book_path(sem)
    p.parent.mkdir(parents=True, exist_ok=True)
    text = book_tex(course, sem, repo)
    if not p.exists() or p.read_text(encoding="utf-8") != text:
        p.write_text(text, encoding="utf-8")
    return p

