    def sample(self, rng):
        cfg = self.cfg
        q, e = rng.choice(cfg.pairs)
        N = q**e
        p = rng.choice([p for p in PRIMES if cfg.p_lo <= p <= cfg.p_hi and (p - 1) % N == 0])
        while True:
            a = rng.randrange(2, p - 1)
            g = pow(a, (p - 1) // N, p)
            if pow(g, N // q, p) != 1:
                break
        if rng.random() < cfg.special_ratio:
            kind = rng.choice(["one", "one", "inv", "top", "low"])
            x = {"one": 0, "inv": N - 1, "top": rng.randrange(1, q) * q ** (e - 1),
                 "low": rng.randrange(1, q)}[kind]
        else:
            x = rng.randrange(2, N)
        h = pow(g, x, p)
        terms = ["x_0"] + [f"x_{{{i}}} \\cdot {q}" + (f"^{{{i}}}" if i > 1 else "") for i in range(1, e)]
        if e > 4:
            terms = terms[:3] + [r"\dots"] + terms[-1:]
        return {"g": g, "h": h, "p": p, "q": q, "e": e, "N": N, "digits_tex": " + ".join(terms),
                "s": digit_steps(g, h, q, e, p), "answer": x}

    def check(self, p):
        g, h, P, q, e, N, x = (p[k] for k in ("g", "h", "p", "q", "e", "N", "answer"))
        assert N == q**e and (P - 1) % N == 0 and is_order(g, N, P)
        # independent: exhaustive search over the cyclic group <g>
        assert [k for k in range(N) if pow(g, k, P) == h] == [x]
        assert sum(r["xi"] * q ** r["i"] for r in p["s"]["rows"]) == x
        assert all(0 <= r["xi"] < q for r in p["s"]["rows"])
