import yaml
from click.testing import CliRunner

from taskgen.cli import main
from taskgen.core import course as c
from taskgen.core import exam as ex

REPO = Path(__file__).resolve().parents[2]

MINI_COURSE = {
    "semesters": [{
        "n": 1, "title": "Тест", "exam_questions": 3,
        "lectures": [
            {"n": 1, "slug": "intro", "title": "Введение"},
            {"n": 2, "slug": "mult", "title": "Умножение", "topics": ["arithmetic.multiplication"],
             "exam_questions": ["sem1:1", "sem1:2", "sem1:3"]},
            {"n": 3, "slug": "euclid", "title": "Евклид", "topics": ["number_theory.euclid"]},
        ],
    }],
}

MINI_EXAM = {
    "title": "Вопросы на зачёт", "genitive": "вопросов на зачёт", "date": "декабрь 2026",
    "literature": ["knuth-taocp2", "msu-ent"],
    "topics": [{"title": "Арифметика в $\\Zn{n}$", "questions": [
        {"id": "sem1:1", "text": "Умножение Карацубы.",
         "refs": [{"key": "knuth-taocp2", "loc": "Раздел 4.3"}, {"key": "msu-ent", "sep": " "}]},
        {"id": "sem1:2", "text": ["Первая часть.", "Вторая часть."], "lectures": [2],
         "refs": [{"text": "не скажу ☺"}]},
    ]}],
}


def _exam(**changes):
    data = yaml.safe_load(yaml.safe_dump(MINI_EXAM, allow_unicode=True))
    data.update(changes)
    return data


@pytest.fixture
def mini_repo(tmp_path):
    shutil.copytree(REPO / "latex", tmp_path / "latex")
    (tmp_path / "materials/sem1/exam").mkdir(parents=True)
    (tmp_path / "materials/sem1/exam/questions.yaml").write_text(
        yaml.safe_dump(MINI_EXAM, allow_unicode=True), encoding="utf-8")
    return tmp_path


def test_real_lists_load_and_match_course():
    crs = c.load_course()
    for s in crs.semesters:
        e = ex.load_sem(s.n)
        assert e is not None and e.count == s.exam_questions
        assert set(e.literature) <= ex.bib_keys()
        # the committed body is up to date
        assert (REPO / ex.body_path(s.n)).read_text(encoding="utf-8") == ex.render(e, ex.questions_path(s.n))
    sem1 = ex.load_sem(1)
    assert [q.label for q in sem1.questions()][13:16] == ["14-15", "16", "17"]
    sem2 = ex.load_sem(2)
    assert [q.id for q in sem2.questions() if q.new] == ["sem2:25", "sem2:26", "sem2:27", "sem2:28"]
    probs = [p for p in ex.check(crs) if p[0] == "error"]
    assert probs == []


def test_render():
    e = ex.ExamQuestions.model_validate(MINI_EXAM)
    tex = ex.render(e, "q.yaml")
    assert tex.startswith("% Generated by `taskgen exam render` from q.yaml.")
    assert r"\examtitle[вопросов на зачёт]{Вопросы на зачёт}{декабрь 2026}" in tex
    assert r"\examliterature{knuth-taocp2,msu-ent}" in tex
    assert r"\question{1}{Умножение Карацубы.}{\cite[Раздел 4.3]{knuth-taocp2} \cite{msu-ent}}" in tex
    assert r"\begin{questiongroup}{2}{3}{не скажу ☺}" in tex
    assert "  \\qpart{Вторая часть.}\n\\end{questiongroup}" in tex
    one = _exam(topics=[{"title": "T", "questions": [{"id": "sem1:1", "text": "Два номера.", "span": 2}]}])
    assert r"\question{1--2}{Два номера.}{}" in ex.render(ex.ExamQuestions.model_validate(one))


@pytest.mark.parametrize("change, msg", [
    ({"topics": [{"title": "T", "questions": [{"id": "sem1:2", "text": "x"}]}]}, "expected number 1"),
    ({"topics": [{"title": "T", "questions": [{"id": "sem1:1", "text": ["a"], "span": 2}]}]}, "span 2"),
    ({"topics": [{"title": "T", "questions": [{"id": "sem1:1", "text": "a",
                                                 "refs": [{"key": "hps"}]}]}]}, "not in `literature`"),
    ({"topics": [{"title": "T", "questions": [{"id": "sem1:1", "text": "a",
                                                 "refs": [{"key": "hps", "text": "x"}]}]}]}, "exactly one"),
    ({"literature": ["hps", "hps"]}, "duplicate literature"),
])
def test_schema_errors(change, msg):
    with pytest.raises(ValueError, match=msg):
        ex.ExamQuestions.model_validate(_exam(**change))


def test_check_and_render_all(mini_repo):
    crs = c.Course.model_validate(MINI_COURSE)
    probs = ex.check(crs, mini_repo)
    text = "\n".join(f"{lvl} {w}: {m}" for lvl, w, m in probs)
    assert "error materials/sem1/exam/questions-body.tex: stale or missing" in text
    # lecture 3 has topics but no questions; the intro lecture (no topics) is exempt
    assert "warning materials/sem1/lectures/03-euclid: lecture has no exam questions" in text
    assert "01-intro" not in text
    assert [r.status for r in ex.render_all(crs, mini_repo, write=False)] == ["stale"]
    assert [r.status for r in ex.render_all(crs, mini_repo)] == ["written"]
    assert [r.status for r in ex.render_all(crs, mini_repo)] == ["ok"]
    assert not any("stale" in m for _, _, m in ex.check(crs, mini_repo))

    data = yaml.safe_load(yaml.safe_dump(MINI_COURSE))
    data["semesters"][0]["exam_questions"] = 4
    data["semesters"][0]["lectures"][1]["exam_questions"] = ["sem1:1", "sem1:2"]
    data["semesters"][0]["lectures"][2]["exam_questions"] = ["sem1:3"]
    text = "\n".join(m for _, _, m in ex.check(c.Course.model_validate(data), mini_repo))
    assert "3 question numbers, course.yaml says exam_questions: 4" in text
    assert "question 2-3: lectures [2] != course.yaml [2, 3]" in text


def test_check_literature_topics_and_sheet(mini_repo):
    e = _exam(literature=["knuth-taocp2", "msu-ent", "no-such-key"], sheet="sheets/none.yaml")
    e["topics"][0]["questions"][0]["topics"] = ["no.such"]
    (mini_repo / "materials/sem1/exam/questions.yaml").write_text(
        yaml.safe_dump(e, allow_unicode=True), encoding="utf-8")
    text = "\n".join(m for _, _, m in ex.check(c.Course.model_validate(MINI_COURSE), mini_repo))
    assert "literature key 'no-such-key' not in latex/ca-refs.bib" in text
    assert "question 1: topic 'no.such' not in taxonomy" in text
    assert "exam sheet sheets/none.yaml missing" in text


def test_coverage_of_the_real_exam_sheets():
    crs = c.load_course()
    for s in crs.semesters:
        e = ex.load_sem(s.n)
        assert e.sheet and (REPO / e.sheet).exists()
        cov = ex.coverage(e, s)
        assert [qc.question.label for qc in cov if not qc.covered] == []
    lattice = [qc for qc in ex.coverage(ex.load_sem(2), crs.semester(2)) if qc.question.first == 28][0]
    assert lattice.slots == ["Решётки"] and "crypto.congruential" in lattice.tasks


def test_cli_render_check_and_coverage():
    r = CliRunner().invoke(main, ["exam", "render", "--check"])
    assert r.exit_code == 0, r.output
    assert "ok       materials/sem1/exam/questions-body.tex" in r.output
    r = CliRunner().invoke(main, ["exam", "coverage", "--sem", "2"])
    assert r.exit_code == 0 and "sheets/sem2/exam.yaml covers 20/20 questions" in r.output
    assert "ok  14-15" not in r.output and "ok  12-14" in r.output
